"""Bundle art/dots/*.json into src/sprites.ts."""
import json, os
m = {'hamster': 'hamster-c-small', 'spitter': 'tower-spitter', 'cannon': 'tower-cannon', 'coil': 'tower-coil', 'fog': 'tower-fog',
     'mite': 'bug-mite', 'zip': 'bug-zip', 'beetle': 'bug-beetle', 'jammer': 'bug-jammer'}
out = {}
for k, f in m.items():
    p = f'art/dots/{f}.json'
    if os.path.exists(p):
        d = json.load(open(p)); out[k] = {'palette': d['palette'], 'rows': d['rows']}
open('src/sprites.ts', 'w').write("// LED dot sprites, generated by scripts/dotify.py from art/ (GPT Image / Nano Banana pixel art).\n// Each row is one line of dots; letters index the palette, '.' is an unlit dot.\nexport interface DotSprite { palette: Record<string, string>; rows: string[] }\nexport const SPRITES: Record<string, DotSprite> = " + json.dumps(out) + ";\n")
print('sprites:', sorted(out))
